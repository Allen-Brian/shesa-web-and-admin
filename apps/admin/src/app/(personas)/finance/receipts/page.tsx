import { redirect } from 'next/navigation';
import { headers } from 'next/headers';

import { getServerClient } from '@/lib/supabase-server';

import { ReceiptsView, type ReceiptRow } from './widgets/receipts-view';

export const dynamic = 'force-dynamic';

export const metadata = { title: 'Shesa Finance — Receipts' };

interface RawReceiptRow {
  readonly token: string;
  readonly payment_id: string;
  readonly receipt_number: string;
  readonly created_at: string;
}

interface RawPaymentRow {
  readonly id: string;
  readonly charge_id: string | null;
  readonly scope_id: string;
  readonly payer_member_id: string | null;
  readonly amount: string;
  readonly currency: string;
  readonly method: string;
  readonly source: string;
  readonly reverses_payment_id: string | null;
  readonly metadata: Record<string, unknown> | null;
  readonly created_at: string;
}

interface RawChargeRow {
  readonly id: string;
  readonly name: string;
  readonly shape: string;
}

interface RawScopeRow {
  readonly id: string;
  readonly name: string;
}

interface RawMemberRow {
  readonly id: string;
  readonly full_name: string;
}

/**
 * Receipts page — every receipt token auto-generated by the M5 trigger.
 *
 * Each row joins to its payment for amount + payer info, and to the
 * charge for context. The printable-receipt dialog carries the same
 * fields plus the public verification URL (rendered via the /verify
 * route which is anonymous-callable).
 */
export default async function ReceiptsPage() {
  const supabase = await getServerClient();
  const {
    data: { user },
  } = await supabase.auth.getUser();
  if (!user) redirect('/login?next=/finance/receipts');

  const [{ data: receiptsRaw }, { data: paymentsRaw }] = await Promise.all([
    supabase
      .schema('finance' as never)
      .from('receipt_verifications' as never)
      .select('token, payment_id, receipt_number, created_at')
      .order('created_at', { ascending: false })
      .limit(500),
    supabase
      .schema('finance' as never)
      .from('payments' as never)
      .select(
        'id, charge_id, scope_id, payer_member_id, amount, currency, method, source, reverses_payment_id, metadata, created_at',
      )
      .order('created_at', { ascending: false })
      .limit(1000),
  ]);

  const receiptsData = (receiptsRaw ?? []) as RawReceiptRow[];
  const paymentsData = (paymentsRaw ?? []) as RawPaymentRow[];
  const paymentById = new Map(paymentsData.map((p) => [p.id, p]));

  const chargeIds = Array.from(
    new Set(paymentsData.map((p) => p.charge_id).filter((id): id is string => !!id)),
  );
  const scopeIds = Array.from(new Set(paymentsData.map((p) => p.scope_id)));
  const memberIds = Array.from(
    new Set(paymentsData.map((p) => p.payer_member_id).filter((id): id is string => !!id)),
  );

  const [{ data: chargeRows }, { data: scopeRows }, { data: memberRows }] = await Promise.all([
    chargeIds.length
      ? supabase
          .schema('finance' as never)
          .from('charges' as never)
          .select('id, name, shape')
          .in('id', chargeIds)
      : Promise.resolve({ data: [] as RawChargeRow[] }),
    scopeIds.length
      ? supabase.schema('core').from('scopes').select('id, name').in('id', scopeIds)
      : Promise.resolve({ data: [] as RawScopeRow[] }),
    memberIds.length
      ? supabase.schema('core').from('members').select('id, full_name').in('id', memberIds)
      : Promise.resolve({ data: [] as RawMemberRow[] }),
  ]);
  const chargeById = new Map(((chargeRows ?? []) as RawChargeRow[]).map((c) => [c.id, c]));
  const scopeById = new Map(((scopeRows ?? []) as RawScopeRow[]).map((s) => [s.id, s]));
  const memberById = new Map(((memberRows ?? []) as RawMemberRow[]).map((m) => [m.id, m]));

  const reversedIds = new Set(
    paymentsData.map((p) => p.reverses_payment_id).filter((id): id is string => !!id),
  );

  // Resolve base URL for the verify link. In prod, the request's host
  // header carries the deployed domain; locally it's the dev server.
  const hdrs = await headers();
  const host = hdrs.get('host') ?? 'localhost:3000';
  const proto = host.startsWith('localhost') || host.startsWith('127.') ? 'http' : 'https';
  const baseUrl = `${proto}://${host}`;

  const receipts: ReceiptRow[] = receiptsData
    .map((r) => {
      const payment = paymentById.get(r.payment_id);
      if (!payment) return null;
      const charge = payment.charge_id ? chargeById.get(payment.charge_id) : null;
      const scope = scopeById.get(payment.scope_id);
      const member = payment.payer_member_id ? memberById.get(payment.payer_member_id) : null;
      const meta = (payment.metadata ?? {}) as {
        donor_name?: string;
        public_donation?: boolean;
      };
      const payerLabel =
        member?.full_name ?? meta.donor_name ?? (meta.public_donation ? 'Anonymous donor' : '—');
      return {
        token: r.token,
        receiptNumber: r.receipt_number,
        paymentId: r.payment_id,
        chargeName: charge?.name ?? '—',
        chargeShape: charge?.shape ?? null,
        scopeName: scope?.name ?? '—',
        payerLabel,
        amount: parseFloat(payment.amount),
        currency: payment.currency,
        method: payment.method,
        isReversal: !!payment.reverses_payment_id,
        isReversed: reversedIds.has(payment.id),
        createdAt: payment.created_at,
      };
    })
    .filter((r): r is ReceiptRow => r !== null);

  return <ReceiptsView receipts={receipts} baseUrl={baseUrl} />;
}
