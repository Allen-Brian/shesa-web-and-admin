#!/usr/bin/env node
/**
 * env:init — generate the .env file for an environment.
 *
 * Usage:
 *   pnpm env:init                # → writes .env.local for this dev machine
 *   pnpm env:init --env local    # → same as above
 *   pnpm env:init --env staging  # → does NOT write a file; prints the
 *   pnpm env:init --env production  checklist of `gh secret set` commands
 *                                    the lead must run to populate GitHub
 *                                    Actions encrypted secrets
 *
 * Local-mode flow:
 *   1. If `supabase status` reports a running stack, capture the URL +
 *      keys + DB URL and write them to .env.local automatically.
 *   2. For every other var, write the local default (defined in env-spec.mjs).
 *   3. For external-service secrets (RESEND_API_KEY), leave a placeholder
 *      with instructions for where to get the value.
 *   4. Refuse to overwrite an existing .env.local unless --force is passed
 *      (otherwise this is a footgun that wipes a dev's working state).
 *
 * Staging/prod flow: never writes secrets to disk. Those values are
 * shared across devs via GitHub Actions encrypted secrets — the lead
 * runs the printed `gh secret set` commands, and CI / production
 * deploys read them at runtime. Devs who need to debug against staging
 * locally fetch values out of band (e.g. `gh secret list` shows what
 * exists; values themselves are never revealed by gh).
 */

import { execSync } from 'node:child_process';
import {
  existsSync,
  writeFileSync,
  readFileSync,
  lstatSync,
  symlinkSync,
  unlinkSync,
} from 'node:fs';
import { join, relative } from 'node:path';
import { ENVS, ENV_VARS, requiredFromUser } from './env-spec.mjs';

const REPO_ROOT = process.cwd();

/**
 * Next.js reads .env.local from the folder containing its next.config,
 * NOT from the workspace root. Rather than duplicate the file per app,
 * symlink the root .env.local into each Next app's directory so both
 * apps + repo root point at the same bytes on disk.
 *
 * Post-pivot (ADR-0040): two apps — admin + web, both Next.js. The
 * retired auth/exco/finance apps came out of this list in the same
 * pass that deleted their source directories.
 */
const NEXT_APP_DIRS = ['apps/admin', 'apps/web'];

// ─────────────────────────────────────────────────────────────────────
// CLI argument parsing — keep it small and explicit; argparse is heavy.
// ─────────────────────────────────────────────────────────────────────
function parseArgs(argv) {
  const args = { env: 'local', force: false };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--env') args.env = argv[++i];
    else if (a === '--force') args.force = true;
    else if (a === '-h' || a === '--help') args.help = true;
  }
  return args;
}

const args = parseArgs(process.argv.slice(2));

if (args.help) {
  console.log(`
env:init — generate .env files / staging+prod setup checklists

Usage:
  pnpm env:init                    # writes .env.local
  pnpm env:init --env staging      # prints gh secret set commands
  pnpm env:init --env production   # prints gh secret set commands
  pnpm env:init --force            # overwrite existing .env.local

  Edit scripts/env-spec.mjs to add/change variables.
`);
  process.exit(0);
}

if (!ENVS.includes(args.env)) {
  console.error(`unknown --env "${args.env}". Pick one of: ${ENVS.join(', ')}`);
  process.exit(1);
}

// ─────────────────────────────────────────────────────────────────────
// Branch: local vs staging/production
// ─────────────────────────────────────────────────────────────────────
if (args.env === 'local') {
  writeLocalEnv();
} else {
  printRemoteChecklist(args.env);
}

// ─────────────────────────────────────────────────────────────────────
// LOCAL: write .env.local
// ─────────────────────────────────────────────────────────────────────
function writeLocalEnv() {
  const file = join(REPO_ROOT, '.env.local');
  if (existsSync(file) && !args.force) {
    console.error(`refusing to overwrite ${file} (use --force to replace).`);
    process.exit(2);
  }

  const supabaseValues = trySupabaseStatus();
  if (!supabaseValues) {
    console.warn(
      '⚠ `supabase status` did not return values — local Supabase may not be running.\n' +
        '  Start it with `pnpm db:start`, then re-run `pnpm env:init --force` to capture keys.\n' +
        '  Continuing with placeholder Supabase values for now.',
    );
  }

  const lines = [
    `# Generated by scripts/env-init.mjs at ${new Date().toISOString()}`,
    `# DO NOT commit this file — .gitignore blocks .env*. Re-generate with: pnpm env:init --force`,
    '',
  ];

  // Group by source for readability — auto/derived first (boring), then
  // supabase-captured, then user-required (loudest at the bottom).
  for (const group of ['auto', 'derived', 'supabase', 'user']) {
    const vars = ENV_VARS.filter((v) => v.source === group);
    if (vars.length === 0) continue;
    lines.push(`# ─── ${group.toUpperCase()} ───`);
    for (const v of vars) {
      const value = resolveLocalValue(v, supabaseValues);
      const placeholder = value === undefined || value === '';
      if (placeholder) {
        lines.push(`# ${v.description}`);
        lines.push(`# REQUIRED: set this before running the affected feature`);
        lines.push(`${v.name}=`);
      } else {
        lines.push(`# ${v.description}`);
        lines.push(`${v.name}=${value}`);
      }
      lines.push('');
    }
  }

  writeFileSync(file, lines.join('\n'), { mode: 0o600 });
  console.log(`✓ wrote ${file} (mode 0600)`);

  linkNextAppEnvs(file);

  const stillMissing = ENV_VARS.filter((v) => {
    const value = resolveLocalValue(v, supabaseValues);
    return value === undefined || value === '';
  });
  if (stillMissing.length > 0) {
    console.log('\nNext steps — fill in these placeholders manually:\n');
    for (const v of stillMissing) {
      console.log(`  ${v.name}`);
      console.log(`    ${v.description}\n`);
    }
  } else {
    console.log('\nAll variables filled. Run `pnpm dev` to start the apps.');
  }
}

/**
 * Symlink the root .env.local into each Next app's directory so
 * `next dev` picks it up. If a real file exists at the target path,
 * leave it alone — the dev may have intentionally overridden values
 * per app.
 */
function linkNextAppEnvs(rootEnvFile) {
  for (const appDir of NEXT_APP_DIRS) {
    const absAppDir = join(REPO_ROOT, appDir);
    if (!existsSync(absAppDir)) continue;
    const target = join(absAppDir, '.env.local');
    const relTarget = relative(absAppDir, rootEnvFile);

    if (existsSync(target)) {
      const stats = lstatSync(target);
      if (!stats.isSymbolicLink()) {
        console.log(
          `⚠ ${target} exists as a regular file — leaving it alone. Delete it and re-run --force to switch to the shared root .env.local.`,
        );
        continue;
      }
      // Already a symlink — refresh in case the path changed.
      unlinkSync(target);
    }
    symlinkSync(relTarget, target);
    console.log(`✓ linked ${target} → ${relTarget}`);
  }
}

function resolveLocalValue(v, supabaseValues) {
  if (v.source === 'auto' || v.source === 'derived') {
    return v.defaults?.local;
  }
  if (v.source === 'supabase' && supabaseValues) {
    return supabaseValues[v.name] ?? v.defaults?.local;
  }
  if (v.source === 'supabase') {
    return v.defaults?.local; // fall back to URL/db-URL defaults; keys stay blank
  }
  if (v.source === 'user') {
    return undefined; // always a placeholder for user-input secrets
  }
  return undefined;
}

/**
 * Run `supabase status -o env --override-name ...` and parse the
 * key=value output. The CLI's `-o env` mode is a stable contract;
 * `--override-name` lets us request the env names we use directly,
 * which avoids a brittle regex pass over the human-readable status.
 *
 * Returns `null` if the command fails or the stack isn't up.
 */
function trySupabaseStatus() {
  // Map Supabase's internal status keys → our env names. Order doesn't
  // matter; --override-name takes multiple values.
  const overrides = [
    'api.url=SHESA_API_URL',
    'auth.anon_key=SHESA_ANON_KEY',
    'auth.service_role_key=SHESA_SERVICE_ROLE_KEY',
    'db.url=SHESA_DB_URL',
  ];

  let raw;
  try {
    raw = execSync(
      `pnpm supabase status -o env ${overrides.map((o) => `--override-name ${o}`).join(' ')}`,
      { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] },
    );
  } catch {
    return null;
  }

  const grab = (name) => {
    // env-mode output is `NAME="value"` per line. Tolerate either quoted
    // or unquoted values, and ignore the pnpm wrapper's lines.
    const m = raw.match(new RegExp(`^${name}="?([^"\\n]+)"?$`, 'm'));
    return m ? m[1].trim() : undefined;
  };

  const apiUrl = grab('SHESA_API_URL');
  const anon = grab('SHESA_ANON_KEY');
  const service = grab('SHESA_SERVICE_ROLE_KEY');
  const dbUrl = grab('SHESA_DB_URL');

  if (!apiUrl || !anon || !service) return null;

  return {
    SUPABASE_URL: apiUrl,
    NEXT_PUBLIC_SUPABASE_URL: apiUrl,
    SUPABASE_ANON_KEY: anon,
    NEXT_PUBLIC_SUPABASE_ANON_KEY: anon,
    SUPABASE_SERVICE_ROLE_KEY: service,
    SUPABASE_DB_URL: dbUrl ?? 'postgresql://postgres:postgres@127.0.0.1:54322/postgres',
  };
}

// ─────────────────────────────────────────────────────────────────────
// STAGING / PRODUCTION: print the checklist
// ─────────────────────────────────────────────────────────────────────
function printRemoteChecklist(env) {
  const envLabel = env.toUpperCase();
  console.log(`
==============================================================================
 ${envLabel} env setup checklist
==============================================================================

Shesa stores ${env} secrets in GitHub Actions encrypted secrets (per
ADR-0020). They live ONCE on the repo and are read by every CI run and
every dev who has admin access. Never write them to disk locally.

Required secrets — run these from the repo root (you'll be prompted for
each value):
`);

  for (const v of ENV_VARS) {
    // staging/prod: every supabase-* var is user-provided (from the
    // Supabase dashboard), since `supabase status` only knows local.
    const hasRemoteDefault = v.defaults?.[env] !== undefined;
    const isAutoOrDerived = v.source === 'auto' || v.source === 'derived';

    if (isAutoOrDerived && hasRemoteDefault) {
      // Known non-secret default for this env → set as repo variable.
      console.log(`  # repo variable (non-secret): ${v.name}=${v.defaults[env]}`);
      console.log(`  gh variable set ${v.name} --env ${env} --body '${v.defaults[env]}'`);
    } else if (isAutoOrDerived && !hasRemoteDefault) {
      // Auto-generated only in local — remote needs a real per-env
      // secret. Print the var's own `generate` hint (e.g. `openssl rand
      // -hex 32`) if one is declared in env-spec.
      console.log(`  # ${v.description}`);
      if (v.generate) console.log(`  # generate: ${v.generate}`);
      console.log(`  gh secret set ${v.name} --env ${env}`);
    } else {
      console.log(`  # ${v.description}`);
      console.log(`  gh secret set ${v.name} --env ${env}`);
    }
    console.log('');
  }

  console.log(`
Audit which secrets are missing on ${env}: pnpm env:check --env ${env}

GitHub CLI required: install with \`brew install gh\` and run \`gh auth login\`.
The repo + environment must already exist in the GitHub UI before secrets can
be set against them. Create the "${env}" environment under
Settings → Environments if it doesn't exist yet.
`);
}
