-- 5. `members.member_code` — column, generator trigger, backfill
-------------------------------------------------------------------------------

ALTER TABLE core.members
  ADD COLUMN IF NOT EXISTS member_code TEXT;

COMMENT ON COLUMN core.members.member_code IS
  'Display id in the shape {batch_year}-{initials}-{4 digits}. Auto-generated by BEFORE INSERT trigger. Unique. NOT NULL after backfill.';

CREATE OR REPLACE FUNCTION core.members_generate_member_code()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  v_year_txt   TEXT;
  v_year_int   INTEGER;
  v_initials   TEXT;
  v_candidate  TEXT;
  v_attempt    INTEGER := 0;
BEGIN
  -- Preserve caller-supplied codes (imports, migrations, tests).
  IF NEW.member_code IS NOT NULL AND length(NEW.member_code) > 0 THEN
    RETURN NEW;
  END IF;

  -- Year prefix — from the member's batch scope. Every batch has an
  -- entry_year; the scope-type trigger already guarantees the FK is a
  -- batch. If the lookup somehow fails, fall back to XXXX rather than
  -- blocking the INSERT.
  SELECT entry_year INTO v_year_int
    FROM core.scopes WHERE id = NEW.batch_scope_id;
  v_year_txt := COALESCE(v_year_int::TEXT, 'XXXX');

  -- Initials — first letter of every whitespace-separated word in
  -- full_name, uppercased. "Sarah Wanki Njumbe" → "SWN".
  SELECT string_agg(upper(left(w, 1)), '' ORDER BY ord)
    INTO v_initials
    FROM (
      SELECT w, row_number() OVER () AS ord
        FROM regexp_split_to_table(COALESCE(NEW.full_name, ''), E'\\s+') AS w
       WHERE length(w) > 0
    ) t;
  IF v_initials IS NULL OR length(v_initials) = 0 THEN
    v_initials := 'X';
  END IF;

  -- Random 4 digits with collision retry. Bounded so a truly-exhausted
  -- (year, initials) namespace surfaces as an error rather than an
  -- infinite loop.
  LOOP
    v_attempt := v_attempt + 1;
    v_candidate := v_year_txt || '-' || v_initials || '-' ||
                   lpad(floor(random() * 10000)::INTEGER::TEXT, 4, '0');
    EXIT WHEN NOT EXISTS (
      SELECT 1 FROM core.members WHERE member_code = v_candidate
    );
    IF v_attempt > 50 THEN
      RAISE EXCEPTION 'members_generate_member_code: no unique code after 50 attempts for %-% (namespace exhausted)',
        v_year_txt, v_initials
        USING ERRCODE = '23505';
    END IF;
  END LOOP;

  NEW.member_code := v_candidate;
  RETURN NEW;
END;
$$;

COMMENT ON FUNCTION core.members_generate_member_code IS
  'BEFORE INSERT: generates members.member_code if not supplied. Format {batch_year}-{initials}-{4 digits}. Bounded retry (50) on collision.';

CREATE TRIGGER members_generate_member_code
  BEFORE INSERT ON core.members
  FOR EACH ROW EXECUTE FUNCTION core.members_generate_member_code();

-- Backfill for any existing rows (defensive; a fresh db reset has none
-- because migrations run before seed).
DO $$
DECLARE
  v_row RECORD;
BEGIN
  FOR v_row IN SELECT id FROM core.members WHERE member_code IS NULL LOOP
    -- Fire the trigger by updating a pass-through column. Simpler:
    -- update the row so BEFORE UPDATE doesn't run (trigger is on
    -- INSERT), so manually generate.
    UPDATE core.members
       SET member_code = (
         SELECT
           COALESCE((SELECT entry_year FROM core.scopes WHERE id = m.batch_scope_id)::TEXT, 'XXXX')
           || '-' ||
           COALESCE(NULLIF(
             (SELECT string_agg(upper(left(w, 1)), '')
                FROM regexp_split_to_table(COALESCE(m.full_name, ''), E'\\s+') AS w
               WHERE length(w) > 0), ''), 'X')
           || '-' ||
           lpad(floor(random() * 10000)::INTEGER::TEXT, 4, '0')
         FROM core.members m WHERE m.id = v_row.id
       )
     WHERE id = v_row.id;
  END LOOP;
END $$;

ALTER TABLE core.members
  ALTER COLUMN member_code SET NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS members_member_code_key
  ON core.members (member_code);
