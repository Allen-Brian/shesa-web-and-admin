-- 2. Redefine `is_admin_role_key` — drop batch_admin
-------------------------------------------------------------------------------
-- Cascades: every function that calls this helper (announcements
-- admin-lens, events admin-lens, last-admin protection trigger,
-- would_be_last_admin RPC) picks up the new definition without
-- edits — the helper is REPLACEd in place.

CREATE OR REPLACE FUNCTION core.is_admin_role_key(role_key TEXT)
RETURNS BOOLEAN
LANGUAGE sql
IMMUTABLE
AS $$
  SELECT role_key IN ('mainstream_admin', 'branch_admin');
$$;

COMMENT ON FUNCTION core.is_admin_role_key IS
  'Returns TRUE if the role key is an admin per Phase 2 §6.1. Post 2026-07-05 batch-admin drop: {mainstream_admin, branch_admin} only.';

