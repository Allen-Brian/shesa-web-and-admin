-- Migration: drop_batch_admin_and_add_member_code
--
-- Two structural changes locked on 2026-07-05:
--
-- 1. **Drop `batch_admin` as a role.** Batches are cluster-only going
--    forward — a filter dimension attached to every member, not a
--    permission-bearing scope. Onboarding new members happens on the
--    Batch details page in Clusters (branch/mainstream admins are the
--    only actors who add members).
--
--    Consequences threaded through this migration:
--      - `core.is_admin_role_key(text)` no longer counts batch_admin.
--        Cascades to every RLS policy and trigger that reads that
--        helper (announcements admin lens, events admin lens, the
--        last-admin protection trigger).
--      - `core.enforce_six_holder_cap` drops batch_admin from its
--        counted set. The 6-holder cap now protects admin + finance
--        (mainstream + branch admins + finance) only.
--      - `core.position_president_prompt` drops batch_admin from the
--        "already an admin, no prompt" check — the check now only
--        exempts mainstream + branch admins.
--
-- 2. **`members.member_code`** — display id in the shape
--    `{entry_year}-{initials}-{4 digits}` (e.g. `2012-SW-0341`,
--    `1973-EBS-2345`). Auto-generated by a BEFORE INSERT trigger if
--    the caller doesn't supply one. Unique + NOT NULL.
--
--    Format details:
--      - `entry_year` is read from `core.scopes.entry_year` for the
--        member's `batch_scope_id`. Every batch scope has one.
--      - `initials` is the uppercase first letter of every whitespace-
--        separated word in `full_name`. "Sarah Wanki Njumbe" → "SWN".
--        Falls back to "X" if the name is empty (defensive; the
--        `contact_required` check makes empty full_names unlikely
--        but not impossible).
--      - `random 4 digits` is uniform in `[0000, 9999]`, retried on
--        collision. Uniqueness is enforced by the UNIQUE index below;
--        the retry loop bounds attempts at 50 so a truly-exhausted
--        (year, initials) namespace surfaces as an error instead of
--        an infinite loop.
--
--    The internal PK stays `id UUID` — member_code is a display /
--    external-reference id, not a FK target.
--
-- 3. **Engagement tier `pillar`** — the 5th and highest tier in the
--    engagement ladder. `dormant < normal < engaged < committed <
--    pillar`. Displayed as 5⭐. "Pillar" reads as the community's
--    load-bearer — a level above merely committed. Enum values stay
--    lowercase, matching every other Shesa enum.

-------------------------------------------------------------------------------
-- 1. Extend engagement_tier with `pillar`
-------------------------------------------------------------------------------

ALTER TYPE core.engagement_tier ADD VALUE IF NOT EXISTS 'pillar';

