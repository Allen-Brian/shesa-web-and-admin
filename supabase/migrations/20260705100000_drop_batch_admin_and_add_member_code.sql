-- 4. Rewrite `position_president_prompt` — drop batch_admin
-------------------------------------------------------------------------------
-- The president-prompt notification fires when a member is assigned
-- the President position but doesn't hold an admin role at the scope.
-- Batch is no longer an admin scope, so the exempted set drops it.

CREATE OR REPLACE FUNCTION core.position_president_prompt()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  v_position_name TEXT;
  v_has_admin     BOOLEAN;
BEGIN
  SELECT name INTO v_position_name
    FROM core.position_catalog WHERE id = NEW.position_catalog_id;

  -- Only fires for President-titled positions.
  IF v_position_name IS NULL OR v_position_name NOT ILIKE 'President%' THEN
    RETURN NEW;
  END IF;

  -- Nothing to prompt if we don't know who to notify.
  IF NEW.assigned_by IS NULL THEN
    RETURN NEW;
  END IF;

  SELECT EXISTS (
    SELECT 1
    FROM core.role_assignments ra
    INNER JOIN core.roles r ON r.id = ra.role_id
    INNER JOIN core.member_accounts ma ON ma.auth_user_id = ra.user_id
    WHERE ma.member_id = NEW.member_id
      AND ma.claim_status = 'claimed'
      AND r.key IN ('mainstream_admin', 'branch_admin')
      AND ra.revoked_at IS NULL
      AND ra.starts_at <= NOW()
      AND (ra.ends_at IS NULL OR ra.ends_at > NOW())
      AND (ra.scope_id IS NULL OR ra.scope_id = NEW.scope_id)
  ) INTO v_has_admin;

  IF v_has_admin THEN
    RETURN NEW;
  END IF;

  INSERT INTO notifications.notification_events (
    event_type,
    severity,
    recipient_user_id,
    scope_id,
    payload
  ) VALUES (
    'position.president_needs_admin',
    'info',
    NEW.assigned_by,
    NEW.scope_id,
    jsonb_build_object(
      'member_id',              NEW.member_id,
      'position_assignment_id', NEW.id,
      'position_name',          v_position_name,
      'channel',                'in_app',
      'hint',                   'This president has no Admin role at this scope. Consider granting.'
    )
  );

  RETURN NEW;
END;
$$;

COMMENT ON FUNCTION core.position_president_prompt IS
  'AFTER trigger on position_assignments: emits an admin-prompt notification when a President is assigned who doesn''t already hold {mainstream_admin, branch_admin} at the scope. Post 2026-07-05: batch_admin removed from the exempted set (batches are no longer an admin scope).';

