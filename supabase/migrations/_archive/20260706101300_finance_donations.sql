-- Migration: finance_donations
--
-- Phase 3 M11 — freewill / public donation path + a donation report.
-- Spec Part V.
--
-- What's already wired without M11:
--   * A charge with shape='donation' can accept payments today via
--     payments/record-manual (admin surface). payer_member_id can be
--     NULL, obligation_id is NULL — the schema and code paths already
--     support the shape.
--
-- What M11 adds:
--   1. finance.record_public_donation(...) — a SECURITY DEFINER RPC
--      callable by anon. Validates that the target charge is a live
--      donation, then INSERTs the payment. Returns the receipt handle
--      (auto-generated by the M5 trigger).
--   2. GRANT USAGE + EXECUTE to anon so the SD seam is reachable from
--      the public website without a user session.
--   3. finance.get_donation_report(scope_id, from, to) — freewill
--      income by charge, mirroring get_collections but filtered to
--      shape='donation'.
--
-- Security notes:
--   * The RPC only accepts charge_id + amount + currency + method +
--     donor_name + donor_email + note. There is NO obligation_id
--     parameter — anon cannot settle a member's dues obligation.
--   * The RPC verifies charge.shape='donation' AND lifecycle IN
--     ('open') AND status='active'. Otherwise it raises 42501/22023
--     with a bland message — no info leak about non-donation charges.
--   * payer_member_id is NEVER set from anon input; even if the donor
--     is a known member, linkage happens as an admin step later.
--   * The M5 receipt trigger fires as normal; the token is returned
--     for the donor's confirmation email / on-screen display.
--   * Rate limiting + captcha is a Cloudflare/edge concern, not
--     enforced here.

-------------------------------------------------------------------------------
-- 1. record_public_donation — the public entry
-------------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION finance.record_public_donation(
  p_charge_id    UUID,
  p_amount       NUMERIC,
  p_currency     TEXT,
  p_method       finance.payment_method,
  p_donor_name   TEXT DEFAULT NULL,
  p_donor_email  TEXT DEFAULT NULL,
  p_note         TEXT DEFAULT NULL
)
RETURNS TABLE (
  payment_id     UUID,
  receipt_token  TEXT,
  receipt_number TEXT
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, finance, public
AS $$
DECLARE
  v_charge     finance.charges%ROWTYPE;
  v_payment_id UUID;
BEGIN
  IF p_amount IS NULL OR p_amount <= 0 THEN
    RAISE EXCEPTION 'amount must be positive' USING ERRCODE = '22023';
  END IF;
  IF p_currency IS NULL OR length(p_currency) <> 3 THEN
    RAISE EXCEPTION 'currency must be ISO 4217' USING ERRCODE = '22023';
  END IF;
  IF p_donor_name IS NOT NULL AND length(p_donor_name) > 200 THEN
    RAISE EXCEPTION 'donor_name too long' USING ERRCODE = '22023';
  END IF;
  IF p_donor_email IS NOT NULL AND length(p_donor_email) > 320 THEN
    RAISE EXCEPTION 'donor_email too long' USING ERRCODE = '22023';
  END IF;
  IF p_note IS NOT NULL AND length(p_note) > 500 THEN
    RAISE EXCEPTION 'note too long' USING ERRCODE = '22023';
  END IF;

  SELECT * INTO v_charge FROM finance.charges WHERE id = p_charge_id;

  -- Bland "not accepting" message on any invalid target — anon should
  -- not be able to distinguish between "no such charge," "not a
  -- donation," "closed," or "paused."
  IF NOT FOUND
     OR v_charge.shape <> 'donation'
     OR v_charge.status <> 'active'
     OR v_charge.lifecycle <> 'open'
     OR v_charge.currency <> upper(p_currency)
  THEN
    RAISE EXCEPTION 'this campaign is not accepting donations'
      USING ERRCODE = '42501';
  END IF;

  -- Public donations flow through the "auto" source seam even in the
  -- simulator, matching how a real MoMo/Orange webhook would confirm.
  INSERT INTO finance.payments
    (obligation_id, charge_id, scope_id, payer_member_id,
     amount, currency, method, source, recorded_by,
     metadata)
  VALUES
    (NULL, v_charge.id, v_charge.scope_id, NULL,
     p_amount, upper(p_currency), p_method, 'auto', NULL,
     jsonb_build_object(
       'public_donation', TRUE,
       'donor_name', p_donor_name,
       'donor_email', p_donor_email,
       'note', p_note
     ))
  RETURNING id INTO v_payment_id;

  -- The M5 receipt trigger fires on the INSERT above. Return the token
  -- for the donor's confirmation.
  RETURN QUERY
  SELECT
    v_payment_id,
    rv.token,
    rv.receipt_number
  FROM finance.receipt_verifications rv
  WHERE rv.payment_id = v_payment_id;
END;
$$;

REVOKE ALL ON FUNCTION finance.record_public_donation(UUID, NUMERIC, TEXT, finance.payment_method, TEXT, TEXT, TEXT) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION finance.record_public_donation(UUID, NUMERIC, TEXT, finance.payment_method, TEXT, TEXT, TEXT)
  TO anon, authenticated, service_role;

COMMENT ON FUNCTION finance.record_public_donation IS
  'Public donation entry. SECURITY DEFINER, anon-executable. Accepts only donation-shape live charges — bland 42501 on any invalid target. payer_member_id is never derived from anon input; the M5 receipt trigger auto-generates the token. Rate limiting + captcha are edge concerns.';

-- Schema USAGE for anon was granted in the M5 receipt migration
-- (finance.verify_receipt). That grant covers this function too.

-------------------------------------------------------------------------------
-- 2. get_donation_report — freewill income by charge
-------------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION finance.get_donation_report(
  p_scope_id UUID,
  p_from     TIMESTAMPTZ DEFAULT NULL,
  p_to       TIMESTAMPTZ DEFAULT NOW()
)
RETURNS TABLE (
  charge_id           UUID,
  charge_name         TEXT,
  donation_count      BIGINT,
  named_donor_count   BIGINT,
  anonymous_count     BIGINT,
  total_donated       NUMERIC(20, 4)
)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, core, finance, public
AS $$
BEGIN
  IF NOT finance.can_read_reports(p_scope_id) THEN
    RAISE EXCEPTION 'finance.report at scope % denied', p_scope_id
      USING ERRCODE = '42501';
  END IF;

  RETURN QUERY
  SELECT
    c.id                                              AS charge_id,
    c.name                                            AS charge_name,
    COUNT(p.id)                                       AS donation_count,
    COUNT(p.id) FILTER (
      WHERE p.payer_member_id IS NOT NULL
         OR (p.metadata->>'donor_name') IS NOT NULL
    )                                                 AS named_donor_count,
    COUNT(p.id) FILTER (
      WHERE p.payer_member_id IS NULL
        AND (p.metadata->>'donor_name') IS NULL
    )                                                 AS anonymous_count,
    COALESCE(SUM(p.amount), 0)                        AS total_donated
  FROM finance.charges c
  LEFT JOIN finance.payments p
    ON p.charge_id = c.id
   AND p.reverses_payment_id IS NULL
   AND NOT EXISTS (
     SELECT 1 FROM finance.payments r WHERE r.reverses_payment_id = p.id
   )
   AND (p_from IS NULL OR p.created_at >= p_from)
   AND p.created_at <= p_to
  WHERE c.scope_id = p_scope_id
    AND c.shape = 'donation'
  GROUP BY c.id, c.name
  ORDER BY total_donated DESC, c.name;
END;
$$;

REVOKE ALL ON FUNCTION finance.get_donation_report(UUID, TIMESTAMPTZ, TIMESTAMPTZ) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION finance.get_donation_report(UUID, TIMESTAMPTZ, TIMESTAMPTZ)
  TO authenticated, service_role;
